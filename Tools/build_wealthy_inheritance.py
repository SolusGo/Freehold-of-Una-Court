"""Generate activation-time clones from the installed BNW / CP v151 schema.

Values are SELECTed when the mod activates; no Bank yields are hardcoded.
Only explicit beneficial columns are doubled. Costs and foreign trader Gold
(TradeRouteTargetBonus) are deliberately excluded.
"""
from princedom_db import database
from validate_mod import ROOT
from validate_mod import GAME_USER_ROOT
from pathlib import Path
import argparse
import hashlib
import json
import re
import xml.etree.ElementTree as ET

CIV = 'CIVILIZATION_TRENT_WEALTHY'
BANK = 'BUILDING_TRENT_WEALTHY_CENTRELINK'
PALACE = 'BUILDING_TRENT_WEALTHY_PALACE'
SCALARS = {'Happiness', 'UnmoddedHappiness', 'SpecialistCount',
           'TradeRouteRecipientBonus'}
# Yield columns in all installed Building_* tables represent intrinsic effects.
# IDs, prerequisites, quantities/costs and flavors are copied unchanged.
BENEFITS = {'Yield', 'YieldChange', 'YieldModifier', 'Happiness', 'NumSpecialists'}
DEFAULT_ASSETS = Path("G:/SteamLibrary/steamapps/common/Sid Meier's Civilization V/Assets")
DEFAULT_CP = GAME_USER_ROOT/'MODS/(1) Community Patch'
SQL_PATH = ROOT/'SQL/110_Wealthy_Inherit.sql'
CONTRACT_PATH = ROOT/'Tools/wealthy_schema.json'


def add_schema_arguments(parser):
    parser.add_argument('--baseline-db',type=Path,help='Read-only pre-collection BNW/CP debug database')
    parser.add_argument('--cp-root',type=Path,default=DEFAULT_CP,help='Installed Community Patch v151 folder')
    parser.add_argument('--game-assets',type=Path,default=DEFAULT_ASSETS,help='Civilization V Assets folder')


def schema_sources(game_assets,cp_root):
    manifests=list(cp_root.glob('*.modinfo'))
    if len(manifests)!=1:raise ValueError(f'Expected one installed CP manifest in {cp_root}')
    manifest=ET.parse(manifests[0]).getroot()
    if manifest.get('id')!='d1b6328c-ff44-4b0d-aad7-c657f83610cd' or manifest.get('version')!='151':
        raise ValueError('Wealthy inheritance targets the installed Community Patch v151 schema')
    known=set()
    for folder in (game_assets/'Gameplay/XML',game_assets/'DLC/Expansion/Gameplay/XML',
                   game_assets/'DLC/Expansion2/Gameplay/XML'):
        if not folder.is_dir():raise ValueError(f'Missing game schema folder: {folder}; use --game-assets')
        for path in sorted(folder.rglob('*.xml')):
            known.update(n.get('name') for n in ET.parse(path).iter('Table') if n.get('name'))
    digest=hashlib.sha256()
    # CP's activation manifest is authoritative; unrelated/stale schema files
    # elsewhere in an installation must not expand the required runtime schema.
    for node in manifest.findall('./Actions/OnModActivated/UpdateDatabase'):
        rel=node.text.replace('\\','/')
        if not rel.startswith('Database Changes/') or rel.startswith('Database Changes/Text/'):continue
        path=cp_root/rel
        digest.update(rel.encode('utf-8')+b'\0'+path.read_bytes().replace(b'\r\n',b'\n')+b'\0')
        if path.suffix=='.xml':
            # The installed Policy XML contains '--' inside a comment, which
            # ElementTree rejects. Strip comments before strict XML parsing;
            # never silently skip a schema document on ParseError.
            source=re.sub(r'<!--.*?-->','',path.read_text(encoding='utf-8-sig'),flags=re.S)
            known.update(n.get('name') for n in ET.fromstring(source).iter('Table') if n.get('name'))
    return known,digest.hexdigest()


def render(db,game_assets=DEFAULT_ASSETS,cp_root=DEFAULT_CP):
    known,fingerprint=schema_sources(game_assets,cp_root)
    actual={r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    missing=sorted(t for t in known-actual if t.startswith('Building_'))
    if missing:raise ValueError('Declared BNW/CP building tables missing from baseline schema: '+', '.join(missing))
    rows = [('Civilizations', 'Type', 'CIVILIZATION_AMERICA', CIV),
            ('Leaders', 'Type', 'LEADER_WASHINGTON', 'LEADER_TRENT_WEALTHY'),
            ('Buildings', 'Type', 'BUILDING_UNA_CENTRELINK', BANK),
            ('Buildings', 'Type', 'BUILDING_PALACE', PALACE)]
    for table, in db.execute("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name"):
        columns = {r[1] for r in db.execute(f'PRAGMA table_info("{table}")')}
        if table in known and table.startswith('Building_') and 'BuildingType' in columns:
            rows.extend((table, 'BuildingType', original, clone) for original, clone in
                        [('BUILDING_UNA_CENTRELINK', BANK), ('BUILDING_PALACE', PALACE)])
    lines = ['-- Generated by Tools/build_wealthy_inheritance.py; reads the active ruleset.',
             '-- Schema contract: Tools/wealthy_schema.json (installed Community Patch v151).',
             '-- Shared Centrelink is defined first. No original rows are updated.']
    contract={'community_patch_version':151,'activated_schema_sha256':fingerprint,'tables':{}}
    for table, key, original, clone in rows:
        columns = {r[1] for r in db.execute(f'PRAGMA table_info("{table}")')}
        edits = [f"{key}='{clone}'"] + (['ID=NULL'] if 'ID' in columns else [])
        if clone == BANK:
            positive = SCALARS if table == 'Buildings' else BENEFITS
            if table == 'Building_FreeSpecialistCounts': positive = positive | {'Count'}
            edits += [f'"{c}"=CASE WHEN "{c}">0 THEN "{c}"*2 ELSE "{c}" END'
                      for c in sorted(columns & positive)]
        required={key}|({'ID'} if 'ID' in columns else set())
        if clone==BANK:required|=columns & positive
        target=contract['tables'].setdefault(table,{})
        info={r[1]:r[2].upper() for r in db.execute(f'PRAGMA table_info("{table}")')}
        for c in sorted(required):target[c]=info[c]
        lines += [f'CREATE TEMP TABLE WealthyClone AS SELECT * FROM "{table}" WHERE {key}=\'{original}\';',
                  'UPDATE WealthyClone SET ' + ', '.join(edits) + ';',
                  f'INSERT INTO "{table}" SELECT * FROM WealthyClone;', 'DROP TABLE WealthyClone;', '']
    return '\n'.join(lines),json.dumps(contract,indent=2,sort_keys=True)+'\n',len(rows)


def audit_schema(db,contract):
    for table,columns in contract['tables'].items():
        found={r[1]:r[2].upper() for r in db.execute(f'PRAGMA table_info("{table}")')}
        if not found:raise ValueError(f'CP v151 inheritance requires table {table}')
        for name,kind in columns.items():
            if name not in found or found[name]!=kind:
                raise ValueError(f'CP v151 inheritance requires {table}.{name} ({kind}); found {found.get(name)}')


def build(baseline_db=None,game_assets=DEFAULT_ASSETS,cp_root=DEFAULT_CP,check=False):
    db=database(baseline_db,cp_root)
    if CONTRACT_PATH.exists():audit_schema(db,json.loads(CONTRACT_PATH.read_text(encoding='utf-8')))
    sql,contract,count=render(db,game_assets,cp_root)
    if check:
        if SQL_PATH.read_text(encoding='utf-8')!=sql or CONTRACT_PATH.read_text(encoding='utf-8')!=contract:
            raise ValueError('Wealthy generated SQL/schema contract is stale; rebuild with the same explicit input paths')
        print(f'PASS: reproducible {count} clones and installed CP v151 schema contract')
    else:
        # Stable Windows checkout bytes also keep packaged ModInfo hashes stable.
        SQL_PATH.write_bytes(sql.replace('\n','\r\n').encode('utf-8'))
        CONTRACT_PATH.write_text(contract,encoding='utf-8')
        print(f'Generated {count} Wealthy clones and CP v151 schema contract')


if __name__ == '__main__':
    parser=argparse.ArgumentParser();add_schema_arguments(parser)
    parser.add_argument('--check',action='store_true',help='Compare generated outputs without writing files')
    args=parser.parse_args()
    build(args.baseline_db,args.game_assets,args.cp_root,args.check)
